from typing import Protocol
from datetime import datetime
from ..contracts import RawSnapshot, OutageEvent, CoverageInterval

class SourceAdapter(Protocol):
    def fetch_snapshot(self, client, observed_at: datetime) -> RawSnapshot: ...
    def normalize(self, snapshot: RawSnapshot) -> list[OutageEvent]: ...
    def audit_snapshot(self, snapshot, previous, policy) -> list[CoverageInterval]: ...
